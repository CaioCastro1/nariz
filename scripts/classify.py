def norm(s: str) -> str:
    import unicodedata
    s = html.unescape(s)
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = re.sub(r"[^A-Za-z0-9 ]+", " ", s).upper()
    return re.sub(r"\s+", " ", s).strip()


def por_regra(nome: str) -> str:
    n = norm(nome)
    for tipo, rx in REGRAS:
        if re.search(rx, n):
            return tipo
    return "Empresa"


