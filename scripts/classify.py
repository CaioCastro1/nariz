def setor_por_regra(nome: str, tipo: str) -> str:
    if tipo in ("Órgão público", "Genérico"):
        return "—"
    if tipo == "Imprensa":
        return "Imprensa e comunicação"
    if tipo == "Internacional":
        return "Organismos internacionais"
    if tipo == "Sociedade civil e academia":
        return "Sociedade civil e academia"
    if tipo == "Sindicato e movimento social":
        return "Trabalho e movimentos sociais"
    n = norm(nome)
    for setor, rx in SETORES:
        if re.search(rx, n):
            return setor
    if tipo == "Estatal e paraestatal":
        return "Sistema S e fomento"
    return "Não classificado"
